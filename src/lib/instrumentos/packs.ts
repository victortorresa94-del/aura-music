/**
 * Los paquetes de muestras: de dónde salen, con qué licencia, cuánto pesan y
 * a quién hay que dar las gracias. Se sirven desde `public/samples/<id>/`, se
 * bajan al abrir el instrumento (la primera carga de la app baja 0 MB) y se
 * guardan en Cache Storage (`aura-samples-v1`) para tocar sin red.
 *
 * Regla de la casa: solo CC0, dominio público o CC-BY con crédito. Nada GPL,
 * NC ni SA. Si la licencia de una fuente no está clara, no entra: el
 * instrumento suena sintetizado (ver `sinte.ts`).
 */

export type PaqueteId =
  | 'piano'
  | 'piano-electrico'
  | 'cuerdas'
  | 'guitarra'
  | 'bajo'
  | 'bateria-acustica'
  | 'cajon'
  | 'percusion-latina'
  | 'bajo-dedos'
  | 'bajo-pua'
  | 'contrabajo'
  | 'metales'
  | 'pizzicato'
  | 'marimba'
  | 'organo'
  | 'guitarra-acero';

export type Licencia = 'CC0-1.0' | 'dominio-publico' | 'CC-BY-4.0' | 'CC-BY-3.0';

export interface ArchivoMuestra {
  /** Nombre del fichero dentro de `public/samples/<id>/`. */
  nombre: string;
  /** Nota MIDI que suena en la muestra. */
  midi: number;
  /** Capa de fuerza del primer formato (piano): «p» o «f». */
  capa?: 'p' | 'f';
  /** Tramo de fuerza MIDI que cubre (formato nuevo). Sin él, toda la fuerza. */
  vel?: [number, number];
  /** Golpe alterno (round robin) dentro de la misma capa: 1, 2... */
  rr?: number;
  bytes: number;
}

/** Cuando un paquete mezcla obras de varios autores: el crédito de cada una. */
export interface FuenteMuestra {
  obra: string;
  autor: string;
  origen: string;
  licencia: Licencia;
  urlLicencia: string;
  creditos: string;
  notas?: number[];
}

export interface Paquete {
  id: PaqueteId;
  /** Cómo se llama en la app. */
  nombre: string;
  /** La obra original, como la nombra su autor. */
  obra: string;
  autor: string;
  /** Página de donde se descargó. */
  origen: string;
  licencia: Licencia;
  urlLicencia: string;
  /** Texto de crédito (obligatorio con CC-BY; vacío con CC0 y dominio público). */
  creditos: string;
  archivos: ArchivoMuestra[];
  /** Ajustes de la envolvente al tocarlo. */
  sonido: { ataque: number; suelta: number };
  /** Percusión: cada muestra suena solo en su nota, sin transportar. */
  percusion?: boolean;
  /**
   * Bucle sobre la parte sostenida de cada muestra, en fracciones de su
   * largo: así una nota mantenida no se corta cuando se acaba la grabación.
   * Solo para sonidos quietos (un órgano), donde la costura no se oye.
   */
  bucle?: { inicio: number; fin: number };
  fuentes?: FuenteMuestra[];
}

